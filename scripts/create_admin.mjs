import crypto from 'node:crypto';
import { getDatabase } from '../server/db.js';
import { hashPassword } from '../server/auth.js';

/**
 * Safe First-Admin Provisioning Utility for MUET Point Tracker
 * Usage:
 *   node scripts/create_admin.mjs --email <email> --name <name> --password <password>
 * Or with environment variables:
 *   ADMIN_EMAIL=admin@muet.edu.pk ADMIN_NAME="Admin" ADMIN_PASSWORD="pwd" node scripts/create_admin.mjs
 */

function parseArgs() {
  const args = process.argv.slice(2);
  const parsed = {};
  for (let i = 0; i < args.length; i++) {
    if (args[i].startsWith('--')) {
      const key = args[i].slice(2);
      const val = args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : true;
      parsed[key] = val;
    }
  }
  return parsed;
}

async function provisionAdmin() {
  console.log('====================================================');
  console.log('  MUET POINT TRACKER — FIRST ADMIN PROVISIONING     ');
  console.log('====================================================\n');

  const args = parseArgs();
  const email = (args.email || process.env.ADMIN_EMAIL || '').trim().toLowerCase();
  const name = (args.name || process.env.ADMIN_NAME || 'Campus Administrator').trim();
  let password = args.password || process.env.ADMIN_PASSWORD;

  if (!email) {
    console.error('Error: Administrator email is required.');
    console.log('Usage: node scripts/create_admin.mjs --email <email> --name <name> --password <password>');
    process.exit(1);
  }

  let autoGenerated = false;
  if (!password) {
    // Generate secure random 16-character password
    password = crypto.randomBytes(12).toString('base64url');
    autoGenerated = true;
  }

  const db = getDatabase();

  // Check if account already exists
  const existing = db.prepare('SELECT id, email, role FROM users WHERE LOWER(email) = ?').get(email);
  const hashedPassword = hashPassword(password);

  if (existing) {
    // Elevate / update existing user
    db.prepare(`
      UPDATE users 
      SET role = 'Admin', name = ?, password_hash = ?
      WHERE id = ?
    `).run(name, hashedPassword, existing.id);

    db.prepare('INSERT INTO audit_logs (action, performed_by) VALUES (?, ?)').run(
      `User account elevated to Admin: ${email}`,
      'CLI Provisioner'
    );

    console.log(`[SUCCESS] Existing user ${email} successfully updated to Admin role!`);
  } else {
    // Create new admin user
    const id = `adm-${Date.now().toString().slice(-4)}`;
    const rollNo = `ADM-${Date.now().toString().slice(-4)}`;

    db.prepare(`
      INSERT INTO users (id, name, email, roll_no, role, department, password_hash)
      VALUES (?, ?, ?, ?, 'Admin', 'Transport Directorate', ?)
    `).run(id, name, email, rollNo, hashedPassword);

    db.prepare('INSERT INTO audit_logs (action, performed_by) VALUES (?, ?)').run(
      `New Admin provisioned: ${email} (${name})`,
      'CLI Provisioner'
    );

    console.log(`[SUCCESS] New Admin user successfully provisioned!`);
    console.log(`  User ID:   ${id}`);
    console.log(`  Name:      ${name}`);
    console.log(`  Email:     ${email}`);
    console.log(`  Roll/ID:   ${rollNo}`);
    console.log(`  Role:      Admin`);
  }

  if (autoGenerated) {
    console.log(`\n  ==================================================`);
    console.log(`  GENERATED ADMIN PASSWORD: ${password}`);
    console.log(`  Please copy and store this password securely!`);
    console.log(`  ==================================================\n`);
  } else {
    console.log('\nPassword has been securely hashed with scrypt and stored.');
  }
}

provisionAdmin().catch((err) => {
  console.error('Provisioning failed:', err);
  process.exit(1);
});
